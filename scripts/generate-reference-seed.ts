/**
 * Writes supabase/seed/reference_data.sql with the global utilities and
 * calls taken from prototype/seed. Run with: npm run seed:reference
 * The SQL can be run again safely: existing rows are updated by slug.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { seedCalls, seedUtilities } from "../src/lib/seed/data";
import { convertCall, convertUtility } from "../src/lib/seed/prototype";

const lit = (v: unknown) => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "object") return `$json$${JSON.stringify(v)}$json$::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

function upsert(table: string, row: Record<string, unknown>, extra: Record<string, string> = {}) {
  const cols = [...Object.keys(row), ...Object.keys(extra)];
  const vals = [...Object.values(row).map(lit), ...Object.values(extra)];
  const updates = cols.filter((c) => c !== "slug").map((c) => `${c} = excluded.${c}`);
  return `insert into public.${table} (${cols.join(", ")})
values (${vals.join(", ")})
on conflict (slug) where org_id is null do update set ${updates.join(", ")};\n`;
}

let sql = `-- Global reference data: utilities and calls maintained by us.
-- Generated by scripts/generate-reference-seed.ts. Do not edit by hand.

begin;

`;
for (const [slug, u] of Object.entries(seedUtilities)) {
  sql += upsert("utilities", { slug, ...convertUtility(u) }) + "\n";
}
for (const [slug, c] of Object.entries(seedCalls)) {
  const { status, ...row } = convertCall(c);
  sql +=
    upsert(
      "calls",
      { slug, ...row },
      {
        status: `${lit(status)}::public.call_status`,
        utility_id: `(select id from public.utilities where slug = ${lit(c.distribuidoraId)} and org_id is null)`,
      },
    ) + "\n";
}
sql += "commit;\n";

const out = join(__dirname, "..", "supabase", "seed", "reference_data.sql");
writeFileSync(out, sql);
console.log(`Wrote ${out}`);
